let users = []
console.log(users)

//Adiciona um item ao final do Array
users.push("Rodrigo")
users.push("João")
users.push("Marcos")

//Adiciona um item ao início do Array
users.unshift("Ana")

console.log(users)

//Remove do início do Array
users.shift()

//Remove do final do Array
users.pop()

console.log(users)