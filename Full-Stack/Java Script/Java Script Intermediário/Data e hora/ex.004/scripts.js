let date= new Date ("July 3, 2024 14:30:00")

console.log(date)

//Modificar ano.
date.setFullYear(2030)

//Modificar o mês (começa com 0)
date.setMonth(1)

//Modificar o dia 
date.setDate(10)

//Modificar a hora
date.setHours(18)

//Modificar o minuto
date.setMinutes(15)

//Modificar segundos.
date.setSeconds(30)


console.log(date)
